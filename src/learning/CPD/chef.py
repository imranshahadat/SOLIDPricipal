class Chef:
    def cook_burger(self) -> None:
        print("Chef: Grilling a juicy burger!")

    def cancel_burger(self) -> None:
        print("Chef: Stopping the burger order.")

    def cook_pizza(self) -> None:
        print("Chef: Baking a hot pepperoni pizza!")

    def cancel_pizza(self) -> None:
        print("Chef: Removing the pizza from the oven.")
